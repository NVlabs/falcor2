def test_render_fallback_docstring_escaping() -> None:
    def Explain(*args: object, **kwargs: object) -> object:
        return object()

    Explain.__doc__ = 'Uses a """quoted""" value from C:\\scene\\file.usd.'
    module = types.ModuleType("falcor2.pxr.Usd")
    module.Explain = Explain
    coverage = stubgen_usd.Coverage(modules=1)

    output = stubgen_usd.StubRenderer("falcor2.pxr", "Usd", {}, coverage).render(module)

    tree = ast.parse(output)
    function = next(node for node in tree.body if isinstance(node, ast.FunctionDef))
    assert ast.get_docstring(function) == Explain.__doc__
