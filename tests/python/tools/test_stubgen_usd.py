import ast
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
import sys
import types


REPO_ROOT = Path(__file__).resolve().parents[3]
STUBGEN_PATH = REPO_ROOT / "external" / "vcpkg_overlays" / "usd" / "stubgen_usd.py"
SPEC = spec_from_file_location("stubgen_usd", STUBGEN_PATH)
assert SPEC is not None and SPEC.loader is not None
stubgen_usd = module_from_spec(SPEC)
sys.modules[SPEC.name] = stubgen_usd
_dont_write_bytecode = sys.dont_write_bytecode
try:
    # The helper lives in a vcpkg overlay port, whose complete directory is
    # hashed into the package ABI. Do not add generated bytecode to that key.
    sys.dont_write_bytecode = True
    SPEC.loader.exec_module(stubgen_usd)
finally:
    sys.dont_write_bytecode = _dont_write_bytecode


def test_parse_docstring_signatures() -> None:
    docstring = """
    **classmethod** Open(filePath, load=...) -> Stage

    filePath : str
    load : InitialLoadSet

    Opens a stage.

    ----------------------------------------------------------------------
    Open(rootLayer, sessionLayer, load=...) -> Stage

    rootLayer : SdfLayerHandle
    sessionLayer : SdfLayerHandle
    load : InitialLoadSet

    Opens a stage from existing layers.
    """

    signatures = stubgen_usd.parse_docstring_signatures(docstring, "Open")

    assert len(signatures) == 2
    assert signatures[0].kind == "class"
    assert signatures[0].parameters == (
        stubgen_usd.Parameter("filePath", "str", False),
        stubgen_usd.Parameter("load", "InitialLoadSet", True),
    )
    assert signatures[0].documentation == "Opens a stage."
    assert signatures[1].return_type == "Stage"
    assert signatures[1].documentation == "Opens a stage from existing layers."


def test_render_boost_style_classmethod() -> None:
    def open_stage(filePath: str, load: object = None) -> object:
        return object()

    open_stage.__doc__ = """
    **classmethod** Open(filePath, load=...) -> Stage

    filePath : str
    load : InitialLoadSet

    Opens a stage from a file.

    ----------------------------------------------------------------------
    Open(filePath, mask) -> Stage

    filePath : str
    mask : bool

    Opens a stage with a population mask.
    """

    class Stage:
        """Represents a composed scene."""

        class InitialLoadSet:
            pass

        Open = staticmethod(open_stage)

    Stage.__module__ = "falcor2.pxr.Usd"
    module = types.ModuleType("falcor2.pxr.Usd")
    module.Stage = Stage
    coverage = stubgen_usd.Coverage(modules=1)
    symbols = stubgen_usd._build_symbol_index("falcor2.pxr", {"Usd": module})

    output = stubgen_usd.StubRenderer("falcor2.pxr", "Usd", symbols, coverage).render(module)

    assert "class Stage:" in output
    assert "class InitialLoadSet:" in output
    assert "@classmethod" in output
    assert "def Open(cls, filePath: str, load: Stage.InitialLoadSet = ...) -> Stage:" in output
    tree = ast.parse(output)
    stage = next(node for node in tree.body if isinstance(node, ast.ClassDef))
    assert ast.get_docstring(stage) == "Represents a composed scene."
    open_methods = [
        node
        for node in stage.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == "Open"
    ]
    assert [ast.get_docstring(method) for method in open_methods] == [
        "Opens a stage from a file.",
        "Opens a stage with a population mask.",
    ]
    assert coverage.documented_callables == 1


def test_normalize_qualified_and_unknown_types() -> None:
    class Frustum:
        class ProjectionType:
            pass

    Frustum.__module__ = "falcor2.pxr.Gf"
    module = types.ModuleType("falcor2.pxr.Gf")
    module.Frustum = Frustum
    coverage = stubgen_usd.Coverage(modules=1)
    symbols = stubgen_usd._build_symbol_index("falcor2.pxr", {"Gf": module})
    resolver = stubgen_usd.TypeResolver("falcor2.pxr", "Gf", symbols, coverage)

    assert resolver.normalize("Frustum.ProjectionType") == "Frustum.ProjectionType"
    assert resolver.normalize("Frustum.MissingType") == "Any"
    assert resolver.normalize("Mapping") == "Mapping[Any, Any]"
    assert resolver.normalize("Span[float]") == "Any"
    assert coverage.unknown_types == 2


def test_render_writable_property() -> None:
    class Spec:
        @property
        def hidden(self) -> bool:
            """type : bool"""
            return False

        @hidden.setter
        def hidden(self, value: bool) -> None:
            pass

    Spec.__module__ = "falcor2.pxr.Sdf"
    module = types.ModuleType("falcor2.pxr.Sdf")
    module.Spec = Spec
    coverage = stubgen_usd.Coverage(modules=1)
    symbols = stubgen_usd._build_symbol_index("falcor2.pxr", {"Sdf": module})

    output = stubgen_usd.StubRenderer("falcor2.pxr", "Sdf", symbols, coverage).render(module)

    assert "def hidden(self) -> bool:" in output
    assert "@hidden.setter" in output
    assert "def hidden(self, value: bool) -> None: ..." in output
    tree = ast.parse(output)
    spec = next(node for node in tree.body if isinstance(node, ast.ClassDef))
    hidden = next(
        node
        for node in spec.body
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == "hidden"
    )
    assert ast.get_docstring(hidden) == "type : bool"


