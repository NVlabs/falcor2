"""Generate directional energy for correlated-Smith GGX, using deterministic VNDF quadrature.

Kulla/Conty compensation requires E(mu, roughness) for unit Fresnel and its cosine
average. Nodes include both endpoints; the cosine axis is sqrt(mu), concentrating
samples near grazing. The average integrates the same interpolant used by the GPU.
No renderer-specific prefiltered-environment coefficients are used.
"""

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np


def _radical_inverse(indices: np.ndarray) -> np.ndarray:
    bits = indices.astype(np.uint32).copy()
    bits = (bits << 16) | (bits >> 16)
    bits = ((bits & 0x55555555) << 1) | ((bits & 0xAAAAAAAA) >> 1)
    bits = ((bits & 0x33333333) << 2) | ((bits & 0xCCCCCCCC) >> 2)
    bits = ((bits & 0x0F0F0F0F) << 4) | ((bits & 0xF0F0F0F0) >> 4)
    bits = ((bits & 0x00FF00FF) << 8) | ((bits & 0xFF00FF00) >> 8)
    return bits.astype(np.float64) / 2**32


def directional_energy(mu: float, roughness: float, count: int) -> float:
    """Integral of unit-Fresnel D*G/(4*mu), sampled with the visible-normal proposal."""
    if roughness == 0 or mu == 0:
        return 1.0
    index = np.arange(count, dtype=np.uint32)
    u = (index.astype(np.float64) + 0.5) / count
    v = _radical_inverse(index)
    alpha = roughness * roughness
    wi = np.array([np.sqrt(1 - mu * mu), 0, mu])
    stretched = wi * [alpha, alpha, 1]
    stretched /= np.linalg.norm(stretched)
    z = (1 - v) * (1 + stretched[2]) - stretched[2]
    radius = np.sqrt(np.maximum(1 - z * z, 0))
    h = np.stack([radius * np.cos(2 * np.pi * u), radius * np.sin(2 * np.pi * u), z], axis=-1)
    h = (h + stretched) * [alpha, alpha, 1]
    h /= np.linalg.norm(h, axis=-1, keepdims=True)
    wo = 2 * (h @ wi)[:, None] * h - wi
    positive = wo[:, 2] > 1e-6
    no = np.maximum(wo[:, 2], 1e-6)
    lambda_i = (np.sqrt(1 + alpha**2 * (1 - mu**2) / mu**2) - 1) / 2
    lambda_o = (np.sqrt(1 + alpha**2 * (1 - no**2) / no**2) - 1) / 2
    return float(np.mean(np.where(positive, (1 + lambda_i) / (1 + lambda_i + lambda_o), 0)))


def generate(resolution: int, samples: int) -> tuple[np.ndarray, dict]:
    axis = np.linspace(0, 1, resolution)
    energy = np.empty((resolution, resolution), dtype=np.float64)
    maximum_quadrature_difference = 0.0
    for row, roughness in enumerate(axis):
        for col, coordinate in enumerate(axis):
            energy[row, col] = directional_energy(coordinate**2, roughness, samples)
            if row % 8 == 0 and col % 8 == 0:
                half = directional_energy(coordinate**2, roughness, samples // 2)
                maximum_quadrature_difference = max(
                    maximum_quadrature_difference, abs(half - energy[row, col])
                )
    # Integrate in x=sqrt(mu): 2*mu*dmu = 4*x^3 dx. Linear E(x)
    # makes this polynomial, integrated exactly per cell with three Gauss nodes.
    nodes, weights = np.polynomial.legendre.leggauss(3)
    avg = np.zeros(resolution)
    for cell in range(resolution - 1):
        x = (cell + (nodes + 1) / 2) / (resolution - 1)
        t = (nodes + 1) / 2
        values = energy[:, cell, None] * (1 - t) + energy[:, cell + 1, None] * t
        avg += np.sum(values * (4 * x**3) * weights, axis=1) / (2 * (resolution - 1))
    table = np.stack([energy, np.broadcast_to(avg[:, None], energy.shape)], axis=-1).astype(
        np.float32
    )
    return table, {
        "resolution": resolution,
        "samples_per_cell": samples,
        "axes": "x=sqrt(cosine), y=perceptual roughness; endpoint nodes",
        "channels": "directional energy, cosine-average energy",
        "quadrature": "Hammersley spherical-cap GGX VNDF; float64; correlated Smith",
        "max_sparse_half_sample_difference": maximum_quadrature_difference,
        "table_sha256": hashlib.sha256(table.astype("<f4").tobytes()).hexdigest(),
        "reference": "https://google.github.io/filament/main/filament.html#materialsystem/improvingthebrdfs/energylossinspecularreflectance",
    }


def _header_comments(metadata: dict) -> list[str]:
    resolution = metadata["resolution"]
    samples = metadata["samples_per_cell"]
    return [
        "// Generated by tools/generate_gltf_ggx_energy.py; do not edit.",
        f"// Command: python tools/generate_gltf_ggx_energy.py --resolution {resolution} --samples {samples}",
        f"// Table: {resolution} rows x {resolution} columns x 2 channels; row-major float32, channels contiguous.",
        f"// Axes: {metadata['axes']}.",
        f"// Channels: {metadata['channels']}; unit Fresnel.",
        f"// Quadrature: {metadata['quadrature']}.",
        f"// Samples per cell: {samples}.",
        "// Cosine average: exact integration of the piecewise-linear directional-energy interpolant.",
        f"// Maximum sparse half-sample difference: {metadata['max_sparse_half_sample_difference']!r}.",
        f"// Table SHA256 (row-major little-endian float32): {metadata['table_sha256']}",
        f"// Reference: {metadata['reference']}",
    ]


def _write_header(path: Path, table: np.ndarray, metadata: dict) -> None:
    lines = [
        "// SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.",
        "// SPDX-License-Identifier: Apache-2.0",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        *_header_comments(metadata),
        "namespace falcor::detail {",
        f"inline constexpr uint32_t GLTF_GGX_ENERGY_SIZE = {metadata['resolution']};",
        "inline constexpr float GLTF_GGX_ENERGY[] = {",
    ]
    for row in table.reshape(-1, 2):
        lines.append(f"    {float(row[0]):.9e}f, {float(row[1]):.9e}f,")
    lines += ["};", "} // namespace falcor::detail", ""]
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resolution", type=int, default=64)
    parser.add_argument("--samples", type=int, default=32768)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "src/falcor2/render/material/gltf_ggx_energy.h",
    )
    args = parser.parse_args()
    if args.resolution != 64:
        parser.error(
            "the shader lookup uses a fixed 64-node grid; update both consumers before changing it"
        )
    if args.samples < 2:
        parser.error("--samples must be at least 2 for the convergence estimate")
    table, metadata = generate(args.resolution, args.samples)
    _write_header(args.output, table, metadata)
    print(json.dumps(metadata, indent=2))


if __name__ == "__main__":
    main()
